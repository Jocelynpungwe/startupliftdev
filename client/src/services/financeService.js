import api from '../lib/api'
const q=(params={})=>({params:Object.fromEntries(Object.entries(params).filter(([,v])=>v!==''&&v!=null))})
export const getFinanceSummary=(params)=>api.get('/finance/summary',q(params)).then(r=>r.data)
export const getFinanceReport=(params)=>api.get('/finance/reports',q(params)).then(r=>r.data)
export const getIncome=(params)=>api.get('/finance/income',q(params)).then(r=>r.data)
export const createIncome=(data)=>api.post('/finance/income',data).then(r=>r.data)
export const updateIncome=(id,data)=>api.put(`/finance/income/${id}`,data).then(r=>r.data)
export const deleteIncome=(id)=>api.delete(`/finance/income/${id}`).then(r=>r.data)
export const getExpenses=(params)=>api.get('/finance/expenses',q(params)).then(r=>r.data)
export const createExpense=(data)=>api.post('/finance/expenses',data).then(r=>r.data)
export const updateExpense=(id,data)=>api.put(`/finance/expenses/${id}`,data).then(r=>r.data)
export const deleteExpense=(id)=>api.delete(`/finance/expenses/${id}`).then(r=>r.data)
export const getSubscriptions=()=>api.get('/finance/subscriptions').then(r=>r.data)
export const createSubscription=(data)=>api.post('/finance/subscriptions',data).then(r=>r.data)
export const updateSubscription=(id,data)=>api.put(`/finance/subscriptions/${id}`,data).then(r=>r.data)
export const deleteSubscription=(id)=>api.delete(`/finance/subscriptions/${id}`).then(r=>r.data)
